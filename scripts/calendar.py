# Builds docs/social-calendar.md: 14 days of posts from carousels 1-30, with checks.
import json, os, re, datetime as dt
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
car = {c['slug'][:2]: c for c in json.load(open(os.path.join(ROOT, 'docs/social/carousels.json')))}
AI = 'AI characters, written in Greece.'
START = dt.date(2026, 11, 9)  # Monday after the main session returns
PLAN = [  # (carousel number, topic) — mixes food, islands, moving, language; Lefkada never two days running
    ('01', 'food'), ('15', 'Lefkada'), ('06', 'moving'), ('09', 'language'), ('04', 'money'),
    ('21', 'islands'), ('03', 'food'), ('18', 'moving'), ('26', 'Lefkada'), ('11', 'islands'),
    ('16', 'moving'), ('08', 'language'), ('25', 'Athens'), ('20', 'islands'),
]
LEFKADA = {'15', '26'}
errors = []
for (a, _), (b, _) in zip(PLAN, PLAN[1:]):
    if a in LEFKADA and b in LEFKADA:
        errors.append(f'Lefkada two days in a row: {a}, {b}')
if len({n for n, _ in PLAN}) != len(PLAN):
    errors.append('a carousel is used twice')
L = ['# Social calendar: 14 days', '',
     f'One carousel a day from {START:%A %-d %B} to {(START + dt.timedelta(days=13)):%A %-d %B %Y}. Images: `social/out/<folder>/` '
     '(`tiktok-01…08.jpg` 1080×1920, `instagram-01…08.jpg` 1080×1350). Captions reuse the checked carousel text only: no new facts. '
     'Each caption ends with the AI label line and 6 hashtags. Generated by `scripts/calendar.py`.', '',
     '| Day | Date | Topic | Carousel | Folder |', '|---|---|---|---|---|']
for i, (n, topic) in enumerate(PLAN):
    c = car[n]
    L.append(f"| {i + 1} | {START + dt.timedelta(days=i):%a %-d %b} | {topic} | {c['title']} | `social/out/{c['slug']}/` |")
L.append('')
for i, (n, topic) in enumerate(PLAN):
    c = car[n]
    body, rest = c['caption'].split(AI)
    tags = rest.split()
    body = body.strip()
    first = re.split(r'(?<=[.?!])\s', body)[0]
    tiktok = f"{first} Full guide: link in bio.\n{AI}\n{' '.join(tags)}"
    insta = f"{body}\n\nSave this for later. The free guide is on our website: link in bio.\n\n{AI}\n{' '.join(tags)}"
    for cap in (tiktok, insta):
        if not cap.split('\n')[-2] == AI or len(cap.split('\n')[-1].split()) != 6:
            errors.append(f'{n}: caption ending')
    L += [f"## Day {i + 1} · {START + dt.timedelta(days=i):%A %-d %B} · {c['title']}", '',
          f"Folder: `social/out/{c['slug']}/` · links to {c['article']}", '',
          '**TikTok caption**', '', '```', tiktok, '```', '',
          '**Instagram caption**', '', '```', insta, '```', '',
          '- [ ] Posted on TikTok  - [ ] Posted on Instagram', '']
if errors:
    raise SystemExit('\n'.join(errors))
open(os.path.join(ROOT, 'docs/social-calendar.md'), 'w').write('\n'.join(L))
print('calendar ok:', len(PLAN), 'days')
